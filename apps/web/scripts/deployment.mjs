// Pure helpers: derive and validate the public frontend configuration from deployments/testnet-demo.json.
// No I/O here so the rules are unit-tested (tests/deployment.test.ts).

export const RPC_URL = "https://test.rpc.fastnear.com";
const ACCOUNT = /^[a-z0-9][a-z0-9._-]{1,62}[a-z0-9]$/;

/** Returns { env, problems }. `env` is only meaningful when `problems` is empty. */
export function deriveEnv(m) {
  const problems = [];
  const need = (cond, msg) => { if (!cond) problems.push(msg); };
  need(m && typeof m === "object", "manifest is not an object");
  if (problems.length) return { env: {}, problems };
  need(m.network === "Testnet", `manifest network is "${m.network}", expected "Testnet"`);
  need(m.verified === true, "manifest is not marked verified");
  const market = m.accounts?.market, token = m.accounts?.token;
  for (const [k, v] of [["accounts.market", market], ["accounts.token", token], ["config.resolver_id", m.config?.resolver_id]]) {
    need(typeof v === "string" && ACCOUNT.test(v) && v.endsWith(".testnet"), `${k} is not a testnet account id: ${JSON.stringify(v)}`);
  }
  need(market !== token, "market and token accounts must differ");
  need(typeof m.market_id === "string" && m.market_id.length > 0, "market_id missing");
  need(m.config?.collateral_token_id === token, `config.collateral_token_id (${m.config?.collateral_token_id}) != accounts.token (${token})`);
  need(m.config?.market_id === m.market_id, `config.market_id (${m.config?.market_id}) != market_id (${m.market_id})`);
  need(m.config?.schema_version === 3, `config.schema_version is ${m.config?.schema_version}, the frontend supports 3`);
  need(m.config?.resolver_id === m.accounts?.resolver_and_token_owner, "config.resolver_id != accounts.resolver_and_token_owner");
  need(Number.isInteger(m.config?.decimals), "config.decimals missing");
  need(m.token_metadata?.decimals === m.config?.decimals, `token decimals (${m.token_metadata?.decimals}) != config.decimals (${m.config?.decimals})`);
  need(typeof m.token_metadata?.symbol === "string" && m.token_metadata.symbol.length > 0, "token_metadata.symbol missing");
  need(m.config?.trading?.price_scale === "1000000", "price_scale must be 1000000");
  need(/^\d+$/.test(m.split_cutoff_ns ?? ""), "split_cutoff_ns missing");
  need(m.market_terms?.split_cutoff_ns === m.split_cutoff_ns, "market_terms.split_cutoff_ns != split_cutoff_ns");
  if (/^\d+$/.test(m.split_cutoff_ns ?? "")) {
    const iso = new Date(Number(BigInt(m.split_cutoff_ns) / 1_000_000n)).toISOString().replace(".000Z", "Z");
    need(m.market_terms?.split_cutoff_utc === iso, `split_cutoff_utc (${m.market_terms?.split_cutoff_utc}) != ${iso} derived from split_cutoff_ns`);
  }
  return {
    problems,
    env: {
      NEXT_PUBLIC_NETWORK: "testnet",
      NEXT_PUBLIC_RPC_URL: RPC_URL,
      NEXT_PUBLIC_MARKET_CONTRACT_ID: market,
      NEXT_PUBLIC_TOKEN_CONTRACT_ID: token,
      NEXT_PUBLIC_MARKET_ID: m.market_id,
    },
  };
}

/** Compares explicitly provided process env values against the manifest: an override that disagrees is an error. */
export function envConflicts(env, processEnv) {
  return Object.entries(env)
    .filter(([k, v]) => processEnv[k] !== undefined && processEnv[k] !== "" && processEnv[k] !== v && !(k === "NEXT_PUBLIC_RPC_URL"))
    .map(([k, v]) => `${k}=${processEnv[k]} disagrees with the manifest (${v})`);
}

export const toDotenv = (env, source) =>
  `# GENERATED by scripts/sync-deployment.mjs from ${source}. Do not edit; run \`pnpm deployment:sync\`.\n` +
  Object.entries(env).map(([k, v]) => `${k}=${v}`).join("\n") + "\n";
